import { createRequire } from "node:module"
import { mysql, pg, type MysqlPool, type PgPool } from "../packages/sql/dist/index.mjs"
import { testSource, type Source } from "../packages/core/dist/kit.mjs"

const require = createRequire(new URL("../examples/express/package.json", import.meta.url))
const columns = { at: "created_at" }

interface Target {
  readonly url: string | undefined
  connect(url: string): { query(sql: string): Promise<unknown>; end(): Promise<void> }
  source(pool: unknown): Source
  readonly create: string
  readonly seeded?: string
}

const targets: Record<string, Target> = {
  pg: {
    url: process.env.PG_URL,
    connect: (url) => new (require("pg").Pool)({ connectionString: url }),
    source: (pool) => pg(pool as PgPool, "item", { columns }),
    create: "CREATE TABLE item (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, tag text, n int NOT NULL, created_at timestamptz NOT NULL, flag boolean NOT NULL)",
    seeded: "ALTER TABLE item ALTER COLUMN id RESTART WITH 100",
  },
  mysql: {
    url: process.env.MYSQL_URL,
    connect: (url) => require("mysql2/promise").createPool({ uri: url, timezone: "Z" }),
    source: (pool) => mysql(pool as MysqlPool, "item", { columns }),
    create: "CREATE TABLE item (id int AUTO_INCREMENT PRIMARY KEY, name varchar(100) NOT NULL, tag varchar(100), n int NOT NULL, created_at datetime(3) NOT NULL, flag boolean NOT NULL)",
  },
}

let failed = 0
let ran = 0
for (const [name, t] of Object.entries(targets)) {
  if (!t.url) continue
  const pool = t.connect(t.url)
  const cases = testSource(async (binding, seed) => {
    await pool.query("DROP TABLE IF EXISTS item")
    await pool.query(t.create)
    const store = t.source(pool).bind(binding)
    for (const row of seed) await store.insert(row)
    if (t.seeded) await pool.query(t.seeded)
    return store
  })
  for (const c of cases) {
    ran++
    try {
      await c.run()
      console.log(`ok    ${name}  ${c.name}`)
    } catch (e) {
      failed++
      console.log(`FAIL  ${name}  ${c.name}\n      ${(e as Error).message}`)
    }
  }
  await pool.end()
}
if (!ran) {
  console.error("usage: PG_URL=<url> MYSQL_URL=<url> node spec/source-sql.ts (one or both)")
  process.exit(2)
}
console.log(failed ? `${failed} of ${ran} failed` : `all ${ran} passed`)
process.exit(failed ? 1 : 0)
