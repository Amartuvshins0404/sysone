import { mysql, pg } from "@sysonejs/sql"
import { createPool } from "mysql2/promise"
import pgLib from "pg"
import type { Row, Source } from "sysonejs/source"
import { category, project, secret, task } from "../model.ts"

const models = { category, project, task, secret }
type Name = keyof typeof models

const tables: Record<Name, { columns: Record<string, string>; pg: string; mysql: string }> = {
  category: {
    columns: { parentId: "parent_id", createdAt: "created_at" },
    pg: "id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, parent_id int, active boolean NOT NULL, size bigint NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now()",
    mysql: "id int AUTO_INCREMENT PRIMARY KEY, name varchar(80) NOT NULL, parent_id int, active boolean NOT NULL, size bigint NOT NULL DEFAULT 0, created_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)",
  },
  project: {
    columns: { tenantId: "tenant_id", ownerId: "owner_id", createdAt: "created_at" },
    pg: "id text PRIMARY KEY, tenant_id text NOT NULL, owner_id text NOT NULL, name text NOT NULL, archived boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL DEFAULT now()",
    mysql: "id varchar(36) PRIMARY KEY, tenant_id varchar(36) NOT NULL, owner_id varchar(36) NOT NULL, name varchar(120) NOT NULL, archived boolean NOT NULL DEFAULT false, created_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)",
  },
  task: {
    columns: { projectId: "project_id" },
    pg: "id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id text NOT NULL, title text NOT NULL",
    mysql: "id int AUTO_INCREMENT PRIMARY KEY, project_id varchar(36) NOT NULL, title text NOT NULL",
  },
  secret: {
    columns: {},
    pg: "id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text NOT NULL",
    mysql: "id int AUTO_INCREMENT PRIMARY KEY, value text NOT NULL",
  },
}

function env(name: string): string {
  const v = process.env[name]
  if (!v) throw new Error(`Set ${name} to a database URL`)
  return v
}

export async function sqlSources(kind: "pg" | "mysql", seed: Record<Name, readonly Row[]>): Promise<Record<Name, Source>> {
  const pgPool = kind === "pg" ? new pgLib.Pool({ connectionString: env("PG_URL") }) : null
  const myPool = kind === "mysql" ? createPool({ uri: env("MYSQL_URL"), timezone: "Z" }) : null
  const run = (sql: string, values: unknown[] = []) => (pgPool ? pgPool.query(sql, values) : myPool!.query(sql, values))
  const out = {} as Record<Name, Source>
  for (const name of Object.keys(models) as Name[]) {
    const { columns } = tables[name]
    const fields = Object.keys(models[name].schema.shape)
    await run(`DROP TABLE IF EXISTS ${name}`)
    await run(`CREATE TABLE ${name} (${tables[name][kind]})`)
    for (const row of seed[name]) {
      const keys = fields.filter((f) => row[f] !== undefined)
      const params = keys.map((_, i) => (pgPool ? `$${i + 1}` : "?"))
      await run(`INSERT INTO ${name} (${keys.map((k) => columns[k] ?? k).join(", ")}) VALUES (${params.join(", ")})`, keys.map((k) => row[k]))
    }
    if (pgPool && typeof seed[name][0]?.id === "number") await run(`SELECT setval(pg_get_serial_sequence('${name}', 'id'), (SELECT max(id) FROM ${name}))`)
    out[name] = pgPool ? pg(pgPool, name, { columns }) : mysql(myPool!, name, { columns })
  }
  return out
}
